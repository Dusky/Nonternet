// Refreshes src/disposable-domains.ts from the public-domain (CC0) disposable-email-domains list (docs/15).
// Run: node scripts/update-disposable.mjs. Operators can also refresh a running site without a rebuild: sitectl disposable-refresh.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const URL_LIST = 'https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf';
const res = await fetch(URL_LIST);
if (!res.ok) throw new Error(`download failed: ${res.status}`);
const domains = (await res.text()).split('\n').map((l) => l.trim().toLowerCase()).filter((l) => l && !l.startsWith('#') && /^[a-z0-9.-]+$/.test(l)).sort();
const out = `// Generated by scripts/update-disposable.mjs from the disposable-email-domains list (CC0 1.0, public domain):
// ${URL_LIST}
// ${domains.length} domains, fetched ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
export const DISPOSABLE_DOMAINS = ${JSON.stringify(domains.join('\n'))};
`;
writeFileSync(fileURLToPath(new URL('../src/disposable-domains.ts', import.meta.url)), out);
console.log(`${domains.length} domains`);
